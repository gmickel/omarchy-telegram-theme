#!/bin/bash
# SPDX-License-Identifier: GPL-3.0-only
set -euo pipefail

project_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
bin_dir="$HOME/.local/bin"
data_dir="${XDG_DATA_HOME:-$HOME/.local/share}/omarchy-telegram-theme"
hook_source="$project_dir/hooks/omarchy-telegram-theme"
generated_dir="$project_dir/generated"
theme_file="$generated_dir/omarchy.tdesktop-theme"
wrapper="$bin_dir/omarchy-telegram-theme"

command -v omarchy >/dev/null 2>&1 || {
  echo "Omarchy is required but was not found." >&2
  exit 1
}
command -v python >/dev/null 2>&1 || {
  echo "Python 3.11 or newer is required but was not found." >&2
  exit 1
}

python -c 'import sys; raise SystemExit(sys.version_info < (3, 11))' || {
  echo "Python 3.11 or newer is required." >&2
  exit 1
}

mkdir -p -- "$generated_dir" "$bin_dir"

OMARCHY_TELEGRAM_THEME_OUTPUT="$theme_file" \
  python "$project_dir/bin/omarchy-telegram-theme" \
  --base-palette "$project_dir/assets/day-custom-base.palette.gz.b64" \
  --check >/dev/null

# Run from this checkout so the generated theme stays self-contained in the repo.
cat >"$wrapper" <<EOF
#!/bin/bash
# SPDX-License-Identifier: GPL-3.0-only
# Generated by omarchy-telegram-theme install.sh — points at the local checkout.
set -euo pipefail
export OMARCHY_TELEGRAM_THEME_OUTPUT=${theme_file@Q}
exec python ${project_dir@Q}/bin/omarchy-telegram-theme \\
  --base-palette ${project_dir@Q}/assets/day-custom-base.palette.gz.b64 \\
  "\$@"
EOF
chmod 755 -- "$wrapper"

install -Dm644 "$project_dir/assets/day-custom-base.palette.gz.b64" \
  "$data_dir/assets/day-custom-base.palette.gz.b64"

omarchy hook install theme-set "$hook_source"

theme_name=$(omarchy theme current 2>/dev/null || true)
theme_slug=$(printf '%s' "$theme_name" | tr '[:upper:]' '[:lower:]' | tr ' ' '-')
"$wrapper" --theme "${theme_slug:-unknown}"

cat >"$generated_dir/README.txt" <<EOF
Omarchy Telegram theme (generated — recreated on every Omarchy theme switch).

Apply ONCE using the normal Telegram UI (do NOT use loadcolors / Ctrl+L):

  1. Open Telegram → Settings → Chat settings
  2. Open the ⋮ menu (top-right of Chat settings)
  3. Choose "Create new theme" → "Import existing theme"
  4. Select this file:
     $theme_file
  5. Click "Keep changes" / Apply

After that, \`omarchy theme set …\` overwrites this same file in place and
Telegram reloads it live. Keep this path — do not copy it to Downloads.
EOF

cat <<EOF

Installed Omarchy Telegram Theme.

Theme file (in this repo):
  $theme_file

One-time activation — use the normal UI (ignore loadcolors / Ctrl+L):
  Settings → Chat settings → ⋮ → Create new theme → Import existing theme
  → pick the file above → Keep changes

A file manager window may already be open on that folder.
EOF
